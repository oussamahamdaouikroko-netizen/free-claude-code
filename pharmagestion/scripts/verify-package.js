'use strict';
/**
 * Verify a packaged build — run after `npm run dist`.
 *
 * This is the script the Windows CI job calls, and the one a maintainer can run
 * locally on Windows. It checks facts, not intentions:
 *
 *   1. the installer exists exactly where the pharmacy expects it, is a real
 *      Windows executable, and is an NSIS installer;
 *   2. the unpacked application contains app.asar, and the asar contains *only*
 *      the application (no tests, no docs, no fixtures, no scripts);
 *   3. better-sqlite3 ships exactly one binary, the Windows x64 one;
 *   4. after a smoke run, the user-data database exists and has the expected
 *      schema — proof that the packaged app created its own database outside
 *      the installation folder.
 *
 * Usage:
 *   node scripts/verify-package.js --smoke-data "%TEMP%\pg-smoke"
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const INSTALLER = path.join(ROOT, 'release', 'PharmaGestion-DZ-Setup.exe');
const UNPACKED = path.join(ROOT, 'release', 'win-unpacked');
const APP_EXE = path.join(UNPACKED, 'PharmaGestion DZ.exe');
const ASAR = path.join(UNPACKED, 'resources', 'app.asar');

const problems = [];
const notes = [];

function ok(message) {
  console.log(`  [ok]   ${message}`);
}

function fail(message) {
  console.log(`  [FAIL] ${message}`);
  problems.push(message);
}

function note(message) {
  console.log(`  [note] ${message}`);
  notes.push(message);
}

function argValue(name) {
  const index = process.argv.indexOf(name);
  return index !== -1 && process.argv[index + 1] ? process.argv[index + 1] : null;
}

/* ------------------------------- 1. installer ------------------------------ */

function checkInstaller() {
  console.log('\n[1/4] Windows installer');
  if (!fs.existsSync(INSTALLER)) {
    fail(`installer not found at ${INSTALLER}`);
    return;
  }
  const stat = fs.statSync(INSTALLER);
  ok(`installer exists: ${INSTALLER}`);
  ok(`size: ${(stat.size / 1024 / 1024).toFixed(1)} MB`);
  if (stat.size < 20 * 1024 * 1024) {
    fail('installer is suspiciously small (< 20 MB): Electron runtime is probably missing');
  }

  const head = Buffer.alloc(64);
  const fd = fs.openSync(INSTALLER, 'r');
  try {
    fs.readSync(fd, head, 0, 64, 0);
  } finally {
    fs.closeSync(fd);
  }
  if (head.toString('latin1', 0, 2) !== 'MZ') {
    fail('installer is not a Windows executable (missing MZ header)');
  } else {
    ok('installer is a Windows PE executable (MZ header)');
  }

  // NSIS installers embed their own banner text; this is a heuristic, not a
  // requirement, so it only produces a note.
  const tail = fs.readFileSync(INSTALLER);
  if (tail.includes(Buffer.from('Nullsoft', 'latin1'))) {
    ok('installer is generated by NSIS (Nullsoft marker found)');
  } else {
    note('NSIS marker not found in the installer body (unusual, but not fatal)');
  }
}

/* --------------------------- 2 and 3. application -------------------------- */

function checkApplication() {
  console.log('\n[2/4] Unpacked application');
  if (!fs.existsSync(APP_EXE)) {
    fail(`application executable not found: ${APP_EXE}`);
    return;
  }
  ok(`application executable: ${APP_EXE}`);

  if (!fs.existsSync(ASAR)) {
    fail(`app.asar not found: ${ASAR}`);
    return;
  }
  ok('app.asar is present');

  let asar;
  try {
    asar = require('@electron/asar');
  } catch (error) {
    note('@electron/asar is unavailable, skipping the content check');
    return;
  }

  const entries = asar.listPackage(ASAR).map((entry) => entry.replace(/\\/g, '/'));
  const forbidden = ['/tests/', '/docs/', '/fixtures/', '/scripts/', '/release/', '/node_modules/.bin'];
  for (const fragment of forbidden) {
    const found = entries.filter((entry) => entry.includes(fragment));
    if (found.length) fail(`development files inside app.asar: ${found.slice(0, 3).join(', ')}`);
  }
  if (!problems.length) ok('app.asar contains the application only (no tests, docs, fixtures, scripts)');

  const required = ['/src/main/index.js', '/src/preload/index.js', '/src/renderer/index.html', '/package.json'];
  for (const entry of required) {
    if (!entries.includes(entry)) fail(`app.asar is missing ${entry}`);
  }

  console.log('\n[3/4] SQLite binary inside the package');
  const prebuilds = path.join(UNPACKED, 'resources', 'app.asar.unpacked', 'node_modules', 'better-sqlite3', 'prebuilds');
  if (!fs.existsSync(prebuilds)) {
    fail(`better-sqlite3 prebuilds are not unpacked: ${prebuilds}`);
    return;
  }
  const binaries = fs.readdirSync(prebuilds).filter((name) => name.endsWith('.node'));
  if (!binaries.includes('win32-x64.node')) {
    fail(`win32-x64.node is missing (found: ${binaries.join(', ') || 'none'})`);
  } else {
    ok('win32-x64.node is packaged');
  }
  const foreign = binaries.filter((name) => name !== 'win32-x64.node');
  if (foreign.length) fail(`foreign binaries packaged: ${foreign.join(', ')}`);
}

/* ------------------------------ 4. smoke run ------------------------------ */

function checkSmokeDatabase(dataDir) {
  console.log('\n[4/4] Smoke-run database');
  if (!dataDir) {
    note('no --smoke-data folder given, skipping the database check');
    return;
  }
  const databaseFile = path.join(dataDir, 'pharmagestion.sqlite');
  if (!fs.existsSync(databaseFile)) {
    fail(`the packaged application did not create its database: ${databaseFile}`);
    return;
  }
  ok(`database created outside the install folder: ${databaseFile}`);

  const Database = require(path.join(ROOT, 'node_modules', 'better-sqlite3'));
  const database = new Database(databaseFile, { readonly: true });
  try {
    const tables = database
      .prepare("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name")
      .all()
      .map((row) => row.name);
    ok(`tables: ${tables.join(', ')}`);
    for (const table of ['settings', 'audit_log']) {
      if (!tables.includes(table)) fail(`table ${table} is missing from the created database`);
    }
    const version = Number(database.pragma('user_version', { simple: true })) || 0;
    if (version < 1) fail('schema version was not recorded');
    else ok(`schema version: v${version}`);
    const defaults = database.prepare('SELECT COUNT(*) AS count FROM settings').get().count;
    if (defaults < 10) fail(`only ${defaults} default settings were seeded`);
    else ok(`default settings seeded: ${defaults}`);

    const integrity = database.pragma('integrity_check');
    const message = Array.isArray(integrity) && integrity.length ? String(integrity[0].integrity_check) : '';
    if (message.toLowerCase() !== 'ok') fail(`integrity_check returned: ${message}`);
    else ok('integrity_check: ok');
  } finally {
    database.close();
  }

  // The installation folder must not contain a database: that is what makes an
  // uninstall or an update harmless.
  const strayDatabase = path.join(UNPACKED, 'pharmagestion.sqlite');
  if (fs.existsSync(strayDatabase)) {
    fail(`a database was written inside the installation folder: ${strayDatabase}`);
  } else {
    ok('no database inside the installation folder');
  }
}

/* --------------------------------- main ----------------------------------- */

function main() {
  console.log('PharmaGestion DZ — packaged build verification');
  checkInstaller();
  checkApplication();
  checkSmokeDatabase(argValue('--smoke-data'));

  console.log('');
  if (problems.length) {
    console.error(`FAILED with ${problems.length} problem(s):`);
    for (const problem of problems) console.error(` - ${problem}`);
    process.exit(1);
  }
  console.log(`PASSED — installer verified at ${INSTALLER}`);
  if (notes.length) {
    console.log(`(${notes.length} note(s): see above)`);
  }
}

if (require.main === module) main();

module.exports = { checkInstaller, checkApplication, checkSmokeDatabase };
