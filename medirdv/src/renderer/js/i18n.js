  const DICT = { fr, ar };
  const LOCALES = { fr: 'fr-DZ', ar: 'ar-DZ-u-nu-latn' };
  let current = localStorage.getItem('medirdv.lang') || 'fr';

  function t(key, vars) {
    const table = DICT[current] || DICT.fr;
    let text = table[key] ?? DICT.fr[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
      }
    }
    return text;
  }

  function setLanguage(lang) {
    current = lang === 'ar' ? 'ar' : 'fr';
    localStorage.setItem('medirdv.lang', current);
    applyDirection();
    document.dispatchEvent(new CustomEvent('language-changed', { detail: { lang: current } }));
  }

  function applyDirection() {
    document.documentElement.lang = current;
    document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
  }

  function getLanguage() {
    return current;
  }

  function locale() {
    return LOCALES[current] || LOCALES.fr;
  }

  /** dd/mm/yyyy */
  function formatDate(isoDay) {
    if (!isoDay) return '';
    const [y, m, d] = String(isoDay).slice(0, 10).split('-');
    if (!y || !m || !d) return String(isoDay);
    return `${d}/${m}/${y}`;
  }

  /** "jeudi 22 octobre 2026" / "الخميس 22 أكتوبر 2026" */
  function formatLong(isoDay) {
    if (!isoDay) return '';
    try {
      const [y, m, d] = String(isoDay).slice(0, 10).split('-').map(Number);
      const date = new Date(Date.UTC(y, m - 1, d));
      return new Intl.DateTimeFormat(locale(), {
        weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
      }).format(date);
    } catch (error) {
      return formatDate(isoDay);
    }
  }

  function formatDateTime(value) {
    if (!value) return '';
    const [datePart, timePart] = String(value).split(' ');
    return `${formatDate(datePart)}${timePart ? ` ${timePart.slice(0, 5)}` : ''}`;
  }

  function formatMoney(amount, currency) {
    const value = Number(amount) || 0;
    const unit = currency || t('common.currency');
    const formatted = new Intl.NumberFormat('fr-DZ', {
      minimumFractionDigits: value % 1 === 0 ? 0 : 2,
      maximumFractionDigits: 2,
    }).format(value);
    return `${formatted} ${unit}`;
  }

  applyDirection();

