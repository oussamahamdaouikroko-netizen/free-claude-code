const STORAGE_KEY = 'rdvdz.locale';

let locale = 'fr';

/** Langue initiale : préférence enregistrée, sinon langue du navigateur. */
export function initLocale() {
  // `sessionStorage` seulement : compatibles avec une CSP stricte et effacé
  // à la fermeture de l'onglet (poste partagé en clinique).
  const stored = sessionStorage.getItem(STORAGE_KEY);
  if (stored === 'ar' || stored === 'fr') {
    locale = stored;
  } else {
    locale = navigator.language?.toLowerCase().startsWith('ar') ? 'ar' : 'fr';
  }
  return locale;
}

export function getLocale() {
  if (!initDone) initLocale();
  return locale;
}

let initDone = false;

export function setLocale(next) {
  locale = next === 'ar' ? 'ar' : 'fr';
  initDone = true;
  sessionStorage.setItem(STORAGE_KEY, locale);
  document.documentElement.lang = locale;
  applyDir();
}

export function applyDir() {
  document.documentElement.dir = getLocale() === 'ar' ? 'rtl' : 'ltr';
}

/**
 * Traduit une clé.
 * @param {string} key
 * @param {Record<string, string|number>} [vars]
 */
export function t(key, vars = undefined) {
  const table = DICT[getLocale()] ?? DICT.fr;
  let value = table[key] ?? DICT.fr[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

/** Vérifie qu'aucune clé française n'est absente de l'arabe (test de parité). */
export function missingArabicKeys() {
  return Object.keys(DICT.fr).filter((key) => !(key in DICT.ar));
}
